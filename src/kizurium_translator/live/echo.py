"""Отбросить кадр, который прочитан как собственный оверлей.

Движок фотографирует экран целиком, и на кадре видны в том числе наши
плашки. Если OCR принял их за текст игры, на экране появляется вторая копия
перевода, и дальше кадр раз за кадром подтверждает сам себя.

Раньше здесь считалась доля кириллицы в прочитанном тексте. Это верно
только когда плашки нарисованы по-русски; при любом другом языке назначения
русский текст на экране выглядел для движка как собственное эхо, и весь кадр
уходил в никуда. Сравнение с тем, что оверлей уже нарисовал, от алфавита не
зависит.

Две функции этого файла вызывались из тела цикла, но определены не были ни
в одном коммите. Блок с вызовом срабатывал ноль раз за всю историю логов,
а на одном наборе окон - доходил и ронял цикл с `NameError`. Оно и молчало:
имя резолвится только в рантайме, а до этой строки код на живой сессии не
доходит на большинстве кадров.
"""

from __future__ import annotations

import re

from .state import State

# Пунктуация не делает строки разными: карточка может прийти с многоточием,
# которого не было в оригинале, а эхом оверлея это не перестаёт быть.
_PUNCT = re.compile(r"[^\w\s]", re.UNICODE)
_SPACE = re.compile(r"\s+")


def overlay_texts(state: State) -> set[str]:
    """Что оверлей уже нарисовал на экране.

    Берутся карточки даже если оверлей скрыт: `peek_blocks` отдаёт их и в
    этом случае, а именно сокрытие означает, что движок мог застать плашки
    предыдущего кадра.

    Каждая карточка даёт и ключ целиком, и ключ каждой строки: карточка
    переносит текст по своим правилам, и движок мог прочесть либо всю её,
    либо только строку.
    """
    out: set[str] = set()
    for block in state.peek_blocks():
        raw = str(block.get("text") or "")
        whole = _key(raw)
        if whole:
            out.add(whole)
        for line in raw.split("\n"):
            key = _key(line)
            if key:
                out.add(key)
    return out


def _key(text: str) -> str:
    """Текст для сравнения: нижний регистр, без пунктуации, схлопнутые пробелы.

    `normalize_for_compare` из `core.text` здесь не годится: он убирает все
    пробелы подряд, потому что им сравнивают текст, приходящий из разных
    проходов OCR. Для сверки «прочитан ли именно нарисованный текст» это
    означало бы, что «Начать квест» и «НачатьКвест» — одно и то же, а
    перенос строки внутри карточки склеивает соседние слова.
    """
    return _SPACE.sub(" ", _PUNCT.sub("", str(text or "").casefold())).strip()


def same_text(text: str, ours: set[str]) -> bool:
    """Читал ли движок то, что нарисовали мы.

    Сравнение по ключу из `overlay_texts`, где лежат и целые карточки, и их
    строки. Своё сравнение по кускам не годится: у плашки перенос там, где в
    оригинале его не было, и ни один фрагмент тогда не совпадёт.
    """
    key = _key(text)
    if not key:
        return False
    if key in ours:
        return True
    # Прочитанная строка может быть многострочным куском карточки, у которой
    # перенос стоит в другом месте.
    return any(key in ours_line for ours_line in ours if " " in ours_line)
